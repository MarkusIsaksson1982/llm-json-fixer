"""Export tests/data/corpus.json into plain fixture files, one folder per failure class,
and write docs/REPAIR-CATALOGUE.md. Re-run after changing the corpus:  python scripts/export_fixtures.py"""
import json, shutil
from pathlib import Path
from llm_json_fixer import core

ROOT = Path(__file__).resolve().parents[1]
FIX = ROOT / "fixtures"
TITLES = {  # heading per failure class, worded the way an agent asks for it
    "fence": "Strip markdown code fences (```json) around LLM JSON output",
    "prose": "Extract JSON from LLM prose (\"Sure! Here is the JSON:\")",
    "trailing_comma": "Remove trailing commas in LLM JSON",
    "single_quotes": "Fix single-quoted keys and strings in LLM JSON",
    "smart_quotes": "Fix smart quotes (curly quotes) in LLM JSON",
    "unquoted_keys": "Fix unquoted keys (JavaScript object literal) in LLM JSON",
    "comments": "Strip // and /* */ comments from LLM JSON",
    "python_literals": "Convert Python literals True / False / None to JSON",
    "special_numbers": "Fix NaN, Infinity, hex and +1 / .5 numbers in LLM JSON",
    "missing_comma": "Insert missing commas between JSON members",
    "mismatched": "Fix mismatched or unbalanced brackets in LLM JSON",
    "escapes": "Fix unescaped quotes and raw newlines inside JSON strings",
    "nested_escaping": "Decode double-encoded (stringified) JSON",
    "truncated": "Repair truncated LLM JSON output (max_tokens cut-off)",
    "concatenated": "Split concatenated JSON objects (JSON Lines without newlines)",
    "unicode": "Unicode, emoji and escape sequences in LLM JSON",
    "combo": "Several LLM JSON errors at once",
    "valid": "Valid JSON passes through unchanged",
    "no_json": "No JSON in the LLM output: refuse instead of hallucinating",
    "schema_coerce": "Coerce LLM JSON to a JSON Schema (\"41\" -> 41, \"yes\" -> true)",
    "schema_validate": "Validate LLM JSON against a JSON Schema",
}

def main():
    corpus = json.loads((ROOT / "tests/data/corpus.json").read_text())
    if FIX.exists(): shutil.rmtree(FIX)
    doc = ["# Repair catalogue: broken LLM JSON and the deterministic fix",
           "", "Generated by `scripts/export_fixtures.py` from the regression corpus. Every example is a fixture in",
           "[`fixtures/`](../fixtures) and runs in `tests/test_fixtures.py`. No LLM call is made for any repair.", ""]
    for cat, title in TITLES.items():
        cases = [c for c in corpus if c["cat"] == cat]
        if not cases: continue
        d = FIX / cat; d.mkdir(parents=True)
        doc += [f"## {title}", "", f"Fixtures: `fixtures/{cat}/`", ""]
        for c in cases:
            if len(c["input"]) > 4000: continue
            (d / f"{c['id']}.input.txt").write_text(c["input"])
            meta = {k: c[k] for k in ("expect", "schema", "valid") if c.get(k) is not None}
            (d / f"{c['id']}.expected.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n")
            r = core.repair(c["input"], schema=c.get("schema"))
            out = json.dumps(r.value, ensure_ascii=False) if r.ok else f"refused: {r.code}"
            fixes = ", ".join(x["fix"] for x in getattr(r, "changes", []) or []) or "none"
            doc += [f"### `{c['id']}`", "", "Input:", "", "~~~~text", c["input"], "~~~~", "",
                    f"Output: `{out}`  ", f"Changes: {fixes}", ""]
    (ROOT / "docs/REPAIR-CATALOGUE.md").write_text("\n".join(doc))

if __name__ == "__main__":
    main()
